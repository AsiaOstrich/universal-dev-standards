#!/usr/bin/env node

/**
 * Bundle ⇄ Source Parity Check
 *
 * Enforces that every `.ai.yaml` standard under the repo-root `.standards/`
 * directory also appears in the npm-bundled copy at `cli/bundled/ai/`
 * (and vice versa), unless explicitly listed in `bundle-exclude.json`.
 *
 * Motivation: DEC-044 / XSPEC-071. When bundled drifts from source, running
 * `uds update` in any adopter project (or worse, in the UDS source repo
 * itself) causes source-of-truth loss.
 *
 * Usage:
 *   node cli/scripts/check-bundle-parity.mjs           # run check, exit 0/1
 *   node cli/scripts/check-bundle-parity.mjs --json    # JSON output
 *
 * Exit codes:
 *   0 — bundled and source match (modulo bundle-exclude.json)
 *   1 — parity mismatch detected (details printed to stdout)
 *   2 — internal error (missing source dir, invalid exclude file, etc.)
 *
 * Note: `cli/bundled/` is generated by `cli/scripts/prepack.mjs` and is
 * gitignored. In CI the check should either run `npm run prepack` first
 * or run against a freshly packed tree. If `cli/bundled/` is absent this
 * script exits 2 with guidance.
 */

import { existsSync, readFileSync, readdirSync, statSync } from 'fs';
import { dirname, join, relative } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const CLI_ROOT = join(__dirname, '..');
const REPO_ROOT = join(CLI_ROOT, '..');
const SOURCE_DIR = join(REPO_ROOT, '.standards');
const BUNDLED_AI_DIR = join(CLI_ROOT, 'bundled', 'ai');
// XSPEC-452 R1: `extensions/` is bundled whole, so it is compared whole — every file, by bytes.
const EXTENSIONS_SOURCE_DIR = join(REPO_ROOT, 'extensions');
const BUNDLED_EXTENSIONS_DIR = join(CLI_ROOT, 'bundled', 'extensions');
const EXCLUDE_CONFIG = join(__dirname, 'bundle-exclude.json');

const args = new Set(process.argv.slice(2));
const JSON_OUTPUT = args.has('--json');

/**
 * Recursively collect all `.ai.yaml` file paths under `root`, returning
 * paths relative to `root` and forward-slash-normalized for stable compare.
 */
function collectAiYaml(root) {
  /** @type {string[]} */
  const results = [];
  if (!existsSync(root)) return results;

  function walk(currentDir) {
    const entries = readdirSync(currentDir);
    for (const entry of entries) {
      const full = join(currentDir, entry);
      const s = statSync(full);
      if (s.isDirectory()) {
        walk(full);
      } else if (s.isFile() && entry.endsWith('.ai.yaml')) {
        results.push(relative(root, full).split('\\').join('/'));
      }
    }
  }

  walk(root);
  return results.sort();
}

/**
 * Recursively collect every file under `root` (any extension), relative and
 * forward-slash-normalized. Absent root → empty list.
 */
function collectAllFiles(root) {
  /** @type {string[]} */
  const results = [];
  if (!existsSync(root)) return results;
  (function walk(currentDir) {
    for (const entry of readdirSync(currentDir)) {
      const full = join(currentDir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (entry !== '.DS_Store') results.push(relative(root, full).split('\\').join('/')); // OS junk: npm never packs it either
    }
  })(root);
  return results.sort();
}

/**
 * XSPEC-452 R1 — `extensions/` ⇄ `cli/bundled/extensions/`, name AND bytes.
 *
 * Why a second comparison and not a wider glob on the first: the `.ai.yaml` check above
 * answers "is every standard installable"; this one answers "does the package carry the
 * add-on files the installer maps to". Until 2026-10-06 nothing compared them, so the
 * published package held 0 of 7 and every parity check stayed green.
 */
function compareExtensions() {
  const source = collectAllFiles(EXTENSIONS_SOURCE_DIR);
  const bundled = collectAllFiles(BUNDLED_EXTENSIONS_DIR);
  const bundledSet = new Set(bundled);
  const sourceSet = new Set(source);
  const missing = source.filter((p) => !bundledSet.has(p));
  const extra = bundled.filter((p) => !sourceSet.has(p));
  const drift = source
    .filter((p) => bundledSet.has(p))
    .filter((p) => !readFileSync(join(EXTENSIONS_SOURCE_DIR, p)).equals(readFileSync(join(BUNDLED_EXTENSIONS_DIR, p))));
  return { source_count: source.length, bundled_count: bundled.length, missing, extra, drift };
}

/**
 * Load exclude list; returns Set of relative paths (e.g. "options/bilingual.ai.yaml").
 */
function loadExcludes() {
  if (!existsSync(EXCLUDE_CONFIG)) return new Set();
  try {
    const content = readFileSync(EXCLUDE_CONFIG, 'utf8');
    const parsed = JSON.parse(content);
    const list = parsed?.excluded_files ?? [];
    return new Set(
      list
        .map((entry) => (typeof entry === 'string' ? entry : entry?.path))
        .filter(Boolean)
    );
  } catch (err) {
    console.error(`[check-bundle-parity] Failed to parse ${EXCLUDE_CONFIG}:`);
    console.error(err.message);
    process.exit(2);
  }
}

function main() {
  if (!existsSync(SOURCE_DIR)) {
    console.error(`[check-bundle-parity] Source directory not found: ${SOURCE_DIR}`);
    process.exit(2);
  }

  if (!existsSync(BUNDLED_AI_DIR)) {
    console.error(`[check-bundle-parity] Bundled directory not found: ${BUNDLED_AI_DIR}`);
    console.error('Run `npm run prepack` inside cli/ first so that bundled/ is generated.');
    process.exit(2);
  }

  const sourceFiles = collectAiYaml(SOURCE_DIR);
  const bundledAll = collectAiYaml(BUNDLED_AI_DIR);
  // Source maps to bundled/ai/standards/<file> for top-level and
  // bundled/ai/options/<subpath> for option files. Strip those prefixes
  // so that relative comparisons align with .standards/ layout.
  const bundledFiles = bundledAll.map((p) => {
    if (p.startsWith('standards/')) return p.slice('standards/'.length);
    return p; // options/... and other subtrees stay as-is
  }).sort();

  // The prefix strip above is one-way; reading the bundled file back needs the
  // same rule applied in reverse, in one place, so the two cannot disagree.
  // Where the bundle was actually built FROM. prepack copies ai/standards →
  // bundled/ai/standards and ai/options → bundled/ai/options.
  const aiSourcePathFor = (rel) => {
    const cands = [join(REPO_ROOT, 'ai', 'standards', rel), join(REPO_ROOT, 'ai', rel)];
    return cands.find((c) => existsSync(c)) ?? null;
  };

  const bundledPathFor = (rel) =>
    existsSync(join(BUNDLED_AI_DIR, 'standards', rel))
      ? join(BUNDLED_AI_DIR, 'standards', rel)
      : join(BUNDLED_AI_DIR, rel);

  const excludes = loadExcludes();
  const sourceSet = new Set(sourceFiles.filter((p) => !excludes.has(p)));
  const bundledSet = new Set(bundledFiles.filter((p) => !excludes.has(p)));

  // Source present but missing in bundle:
  const missingFromBundle = [...sourceSet].filter((p) => !bundledSet.has(p)).sort();
  // Bundle present but missing in source (reverse drift):
  const missingFromSource = [...bundledSet].filter((p) => !sourceSet.has(p)).sort();

  // Present in both, but not the same file.
  //
  // 🔴 Until 2026-09-10 this check compared file NAMES only, and reported
  // "source=185 bundled=185 OK". Its own docstring says it exists because
  // "when bundled drifts from source, running `uds update` causes
  // source-of-truth loss" — and an edited standard is exactly that drift, with
  // both names present the whole time. The failure it was built to prevent was
  // the one shape it could not see, and 185=185 reads like strong evidence.
  //
  // Found from the neighbouring case: cli/bundled/hooks carried a locale pack
  // two commits behind while the hook-delivery gate ran green over it.
  // ⚠️ Compared against `ai/`, NOT against SOURCE_DIR. `.standards/` is this
  // repo's own INSTALLED copy (dogfooding) — prepack builds the bundle from
  // `ai/`, so `.standards/` vs bundled answers a different question and gets it
  // wrong in both directions. The first version of this comparison used
  // SOURCE_DIR and reported 9 drifts, 8 of which were `.standards/` lagging its
  // own source by five months — a real problem, but not this check's.
  // Name parity keeps using SOURCE_DIR: that question (is every standard
  // present) is about the install surface and has its own exclude list.
  const contentDrift = [...sourceSet]
    .filter((p) => bundledSet.has(p))
    .filter((p) => {
      const src = aiSourcePathFor(p);
      if (!src) return false;   // no source file to compare against: not drift
      return readFileSync(src, 'utf8') !== readFileSync(bundledPathFor(p), 'utf8');
    })
    .sort();

  const ext = compareExtensions();
  const extensionsOk = ext.missing.length === 0 && ext.extra.length === 0 && ext.drift.length === 0;

  const ok = missingFromBundle.length === 0 && missingFromSource.length === 0 && contentDrift.length === 0 && extensionsOk;

  if (JSON_OUTPUT) {
    const payload = {
      ok,
      source_count: sourceFiles.length,
      bundled_count: bundledFiles.length,
      excludes: [...excludes].sort(),
      missing_from_bundle: missingFromBundle,
      missing_from_source: missingFromSource,
      content_drift: contentDrift,
      extensions: {
        ok: extensionsOk,
        source_count: ext.source_count,
        bundled_count: ext.bundled_count,
        missing_from_bundle: ext.missing,
        missing_from_source: ext.extra,
        content_drift: ext.drift
      }
    };
    console.log(JSON.stringify(payload, null, 2));
    process.exit(ok ? 0 : 1);
  }

  console.log(`[check-bundle-parity] source=${sourceFiles.length} bundled=${bundledFiles.length} excludes=${excludes.size}`);
  console.log(`[check-bundle-parity] extensions: source=${ext.source_count} bundled=${ext.bundled_count}`);
  if (ok) {
    console.log('[check-bundle-parity] OK — bundle parity holds (modulo excludes).');
    process.exit(0);
  }

  if (missingFromBundle.length > 0) {
    console.log('');
    console.log(`[check-bundle-parity] ${missingFromBundle.length} file(s) in source but NOT in bundle:`);
    for (const p of missingFromBundle) console.log(`  - ${p}`);
  }
  if (missingFromSource.length > 0) {
    console.log('');
    console.log(`[check-bundle-parity] ${missingFromSource.length} file(s) in bundle but NOT in source:`);
    for (const p of missingFromSource) console.log(`  - ${p}`);
  }
  if (contentDrift.length > 0) {
    console.log('');
    console.log(`[check-bundle-parity] ${contentDrift.length} file(s) present in BOTH but with different content:`);
    for (const p of contentDrift) console.log(`  ~ ${p}`);
    console.log('  (the bundle is stale — regenerate it with `npm run prepack`)');
  }
  if (ext.missing.length > 0) {
    console.log('');
    console.log(`[check-bundle-parity] ${ext.missing.length} extension file(s) in extensions/ but NOT in the bundle:`);
    for (const p of ext.missing) console.log(`  - extensions/${p}`);
  }
  if (ext.extra.length > 0) {
    console.log('');
    console.log(`[check-bundle-parity] ${ext.extra.length} extension file(s) in the bundle but NOT in extensions/:`);
    for (const p of ext.extra) console.log(`  - extensions/${p}`);
  }
  if (ext.drift.length > 0) {
    console.log('');
    console.log(`[check-bundle-parity] ${ext.drift.length} extension file(s) present in BOTH but with different bytes:`);
    for (const p of ext.drift) console.log(`  ~ extensions/${p}`);
    console.log('  (the bundle is stale — regenerate it with `npm run prepack`)');
  }
  console.log('');
  console.log('[check-bundle-parity] FAIL — fix by either:');
  console.log('  1. Updating cli/scripts/prepack.mjs copy rules, or');
  console.log('  2. Adding intentional exclusions to cli/scripts/bundle-exclude.json.');
  console.log('');
  console.log('See DEC-044 / XSPEC-071 for context.');
  process.exit(1);
}

main();
