/**
 * The two generated blocks of docs/PRE-RELEASE.md (dev-platform XSPEC-469 R5).
 *
 *   BETA-ACCEPTANCE-TEST      "What to test": rendered from steps.json. Nobody types this list.
 *   BETA-ACCEPTANCE-VERIFIED  "Verified on": rendered from the JSON reports the acceptance program wrote.
 *                             A platform with no report says "not yet verified". It is never filled by hand,
 *                             never from a report of a run that did not install the published package, and never
 *                             from a report that tested nothing.
 *
 * Everything here is a pure function of its inputs: the same steps, CHANGELOG and reports give the same text, so
 * `--check` can compare it with the file byte for byte (no timestamps, no "generated on" line).
 *
 * Standard library only.
 */

import { entryMatchesAnchor } from './changelog.mjs';
import { displayCommand } from './execute.mjs';

export const TEST_BLOCK = 'BETA-ACCEPTANCE-TEST';
export const VERIFIED_BLOCK = 'BETA-ACCEPTANCE-VERIFIED';

const startRe = (name) => new RegExp(`<!-- ${name}:START[^>]*-->`);
const endMarker = (name) => `<!-- ${name}:END -->`;

/** @returns {{ before: string, inner: string, after: string, startLine: string }|null} */
export function splitBlock(text, name) {
  const m = startRe(name).exec(text);
  if (!m) return null;
  const endAt = text.indexOf(endMarker(name), m.index + m[0].length);
  if (endAt === -1) return null;
  return {
    before: text.slice(0, m.index),
    startLine: m[0],
    inner: text.slice(m.index + m[0].length, endAt),
    after: text.slice(endAt + endMarker(name).length),
  };
}

export function startLineOf(name, generator) {
  return `<!-- ${name}:START — generated by ${generator}; edit its inputs, not this block -->`;
}

/** Replace the inside of a block; `null` when the markers are missing. */
export function replaceBlock(text, name, content, generator) {
  const parts = splitBlock(text, name);
  if (!parts) return null;
  return `${parts.before}${startLineOf(name, generator)}\n${content.trim()}\n${endMarker(name)}${parts.after}`;
}

const oneLine = (s) => String(s).replace(/\s+/g, ' ').trim();

function expectSummary(step) {
  const e = step.expect || {};
  if (step.inspect) return `reads ${(e.files || []).map((f) => `\`${f.path}\``).join(', ')}`;
  const parts = [`exit ${[].concat(e.exit === undefined ? 0 : e.exit).join(' or ')}`];
  const text = [...(e.contains || []), ...(e.matches || []).map((m) => `/${m}/`)];
  if (text.length) parts.push(`output has ${text.slice(0, 2).map((t) => `"${oneLine(t)}"`).join(', ')}${text.length > 2 ? ` (+${text.length - 2})` : ''}`);
  return parts.join('; ');
}

/**
 * @param {{ doc: object, blocks: ReturnType<import('./changelog.mjs').parseChangelog>, version: string }} input
 */
export function renderTestList({ doc, blocks, version }) {
  const unreleased = (blocks.find((b) => /^unreleased$/i.test(b.version)) || { entries: [] }).entries;
  const isNew = (step) => (step.changelog || []).some((a) => unreleased.some((e) => entryMatchesAnchor(e, a)));
  const automatic = doc.steps.filter((s) => !s.human);
  const manual = doc.steps.filter((s) => s.human);
  const lines = [];
  lines.push(
    'Run this once on each machine you test on — Windows (PowerShell, cmd or Git Bash), macOS, Linux. It needs Node 20+ and a network. From a clone of the repository:',
    '在你測試的每一台機器上執行一次——Windows（PowerShell、cmd 或 Git Bash）、macOS、Linux。需要 Node 20 以上與網路。在 repository 的複本裡執行：',
    '',
    '```bash',
    `node scripts/beta-acceptance/run.mjs --version ${version}`,
    '```',
    '',
    `It installs the published ${version} into a throwaway folder (not the repository source), runs the steps below that apply to your machine, and writes a report. **Paste the \`.md\` report file back to us** (the \`.json\` next to it is the same report for comparing). An item that needs your eyes is asked in the terminal; with no answer it is recorded as "unconfirmed" and is not counted as passed.`,
    `它把已發布的 ${version} 裝進拋棄式資料夾（不是 repository 原始碼），執行下列適用於你這台機器的步驟，並寫出報告。**請把 \`.md\` 報告檔貼回來**（旁邊的 \`.json\` 是同一份報告，供比對）。需要用眼睛確認的項目會在終端機詢問；沒有回答就記為「未確認」，不計入通過。`,
    '',
    `This list is generated from \`scripts/beta-acceptance/steps.json\`: ${doc.steps.length} steps (${automatic.length} checked by the program, ${manual.length} for a person's eyes). Steps marked **new** test changes that are on \`main\` but not in the published beta yet; against an older beta they are expected to fail.`,
    `本清單由 \`scripts/beta-acceptance/steps.json\` 產生：共 ${doc.steps.length} 步（${automatic.length} 步由程式判定、${manual.length} 步靠人眼）。標 **新** 的步驟測的是已在 \`main\`、但尚未進入已發布測試版的變更；對舊測試版執行時預期會失敗。`,
    '',
  );
  doc.steps.forEach((s, i) => {
    const tags = [s.platform === 'all' ? null : `${s.platform} only`, s.human ? 'needs a person 需人眼' : null, isNew(s) ? '**new 新**' : null].filter(Boolean);
    lines.push(`${i + 1}. \`${s.id}\`${tags.length ? ` (${tags.join('; ')})` : ''} — ${oneLine(s.title)}.`);
    lines.push(`   ${oneLine(s.titleZh)}。`);
    lines.push(`   \`${displayCommand(s)}\` → ${expectSummary(s)}`);
  });
  return lines.join('\n');
}

const PLATFORM_ROWS = [['windows', 'Windows'], ['macos', 'macOS'], ['linux', 'Linux']];

/** Reports that can say a platform was verified: the published package, this version. */
export function eligibleReports(reports, version) {
  return reports.filter(({ report }) => report
    && report.tool === 'uds-beta-acceptance'
    && report.uds && report.uds.version === version
    && report.uds.installKind === 'npm-registry'
    && report.environment && typeof report.environment.platform === 'string'
    && report.counts && Number.isInteger(report.counts.passed));
}

/**
 * @param {{ version: string, reports: Array<{ file: string, report: object }> }} input
 */
export function renderVerified({ version, reports }) {
  const usable = eligibleReports(reports, version);
  const rows = ['| Platform 平台 | Status 狀態 | Details 細節 |', '|---|---|---|'];
  for (const [key, label] of PLATFORM_ROWS) {
    const mine = usable
      .filter(({ report }) => report.environment.platform === key)
      .sort((a, b) => String(b.report.finishedAt).localeCompare(String(a.report.finishedAt)));
    if (!mine.length) {
      rows.push(`| ${label} | Not yet verified 尚未驗證 | no report for ${version} 沒有 ${version} 的報告 |`);
      continue;
    }
    const r = mine[0].report;
    const c = r.counts;
    let status;
    if (r.verdict === 'pass') status = 'Verified 已驗證';
    else if (r.verdict === 'pass_with_unconfirmed') status = `Automated steps passed; ${c.humanUnconfirmed} manual item(s) not confirmed 自動步驟通過；${c.humanUnconfirmed} 項人工尚未確認`;
    else if (r.verdict === 'fail') status = `Failed 有失敗：${c.failed} step(s) 步`;
    else status = 'Not verified (that run tested nothing, or could not run) 未驗證（該次執行沒有測到東西或無法執行）';
    const env = r.environment;
    const day = String(r.finishedAt || '').slice(0, 10) || 'date unknown';
    rows.push(`| ${label} | ${status} | ${env.os.type} ${env.os.release}, Node ${env.node.version}, ${env.shell.value}; ${c.passed} passed / ${c.failed} failed / ${c.skipped} skipped; ${day} |`);
  }
  return [
    `Filled only from the acceptance reports in \`scripts/beta-acceptance/reports/${version}/\` (published package, this version). A platform without a report says "not yet verified".`,
    `只由 \`scripts/beta-acceptance/reports/${version}/\` 裡的驗收報告填入（已發布的套件、這個版本）。沒有報告的平台寫「尚未驗證」。`,
    '',
    ...rows,
  ].join('\n');
}

export const GENERATOR = 'scripts/beta-acceptance/generate-pre-release.mjs';

/**
 * The whole document as it should be. `null` for a block whose markers are missing -> `missing` lists them.
 */
export function generateDocument({ text, doc, blocks, reports, version }) {
  const missing = [];
  let next = text;
  for (const [name, content] of [[TEST_BLOCK, renderTestList({ doc, blocks, version })], [VERIFIED_BLOCK, renderVerified({ version, reports })]]) {
    const replaced = replaceBlock(next, name, content, GENERATOR);
    if (replaced === null) missing.push(name); else next = replaced;
  }
  return { text: next, missing };
}

